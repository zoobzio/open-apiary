import type { Kit } from "./types";

import { extname, join, relative } from "node:path";

import { ENTRY_DIR, ENTRY } from "./constant";
import { json } from "./util";

/** The banner at the top of the entry module. */
const BANNER = "// Generated by @open-apiary/kit. Do not edit by hand.";

/**
 * The import specifier of a source file from the entry module. The path is
 * relative and in POSIX form. A `.ts` extension is removed, so the bundler
 * and the declaration build resolve the file the same way.
 */
const specifier = (from: string, file: string): string => {
  const ext = extname(file);
  const bare = ext === ".ts" ? file.slice(0, -ext.length) : file;
  const rel = relative(from, bare).split("\\").join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
};

/**
 * Makes the source of the entry module. The module imports the default export
 * of each endpoint file and each service file, and exports the bundle: the
 * endpoints by operation id, the service classes, and the OpenAPI document.
 * The bundler takes it as its input, so the bundle has the handlers and the
 * declaration has their types. The document is typed as a record, so the
 * declaration does not repeat it.
 *
 * @param kit - The validated build.
 */
export const entry = (kit: Kit): string => {
  const from = join(kit.root, ENTRY_DIR);
  const lines: string[] = [BANNER];

  kit.endpoints.forEach((endpoint, index) => {
    lines.push(
      `import e${index} from ${JSON.stringify(specifier(from, endpoint.file))};`,
    );
  });
  kit.services.forEach((service, index) => {
    lines.push(
      `import s${index} from ${JSON.stringify(specifier(from, service.file))};`,
    );
  });

  lines.push("");
  lines.push("export const endpoints = {");
  kit.endpoints.forEach((endpoint, index) => {
    lines.push(`  ${JSON.stringify(endpoint.id)}: e${index},`);
  });
  lines.push("};");
  lines.push("");
  lines.push(
    `export const services = [${kit.services.map((_, index) => `s${index}`).join(", ")}];`,
  );
  lines.push("");
  lines.push(
    `export const openapi: Record<string, unknown> = ${json(kit.openapi).trimEnd()};`,
  );
  lines.push("");
  lines.push("export default { endpoints, services, openapi };");
  return `${lines.join("\n")}\n`;
};

/** The path of the entry module, relative to the project root. */
export const entryPath = (): string => join(ENTRY_DIR, ENTRY);
