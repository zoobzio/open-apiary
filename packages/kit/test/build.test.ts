import type { Bundle } from "@open-apiary/schema";

import {
  mkdir,
  readdir,
  readFile,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { isEndpoint, isService } from "@open-apiary/schema";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

import { build, defineConfig, generate } from "../src/build";
import { InvalidConfigError, MissingConfigError } from "../src/error";
import { loadConfig } from "../src/load";
import { PROJECT } from "./helpers";

/** The output directory of the fixture project. */
const DIST = join(PROJECT, ".dist");

/** The generated entry module of the fixture project. */
const ENTRY = join(PROJECT, ".apiary", "index.ts");

/** The ids the fixture source yields, in id order. */
const IDS = ["getHealth", "getUsersById", "postUsers"];

/** Imports a module fresh: the query defeats the module cache. */
const load = async (path: string): Promise<{ default: Bundle }> =>
  import(`${pathToFileURL(path).href}?t=${Date.now()}`);

/** Removes what a build wrote, so the fixture project is as it was. */
const clean = async (): Promise<void> => {
  await rm(DIST, { recursive: true, force: true });
  await rm(join(PROJECT, ".apiary"), { recursive: true, force: true });
};

afterAll(clean);

describe("defineConfig", () => {
  it("returns the config it is given", () => {
    const authored = { source: "./src" };
    expect(defineConfig(authored)).toBe(authored);
  });
});

describe("build", () => {
  let output: Awaited<ReturnType<typeof build>>;

  beforeAll(async () => {
    await clean();
    await mkdir(DIST, { recursive: true });
    await writeFile(join(DIST, "stale.txt"), "left over from an earlier build");
    output = await build({ root: PROJECT });
  }, 60_000);

  it("reports the output directory and the files it wrote", () => {
    expect(output).toEqual({
      outDir: ".dist",
      files: ["index.d.mts", "index.mjs", "openapi.json"],
    });
  });

  it("writes the bundle, the declaration, and the document, and nothing else", async () => {
    expect((await readdir(DIST)).sort()).toEqual([
      "index.d.mts",
      "index.mjs",
      "openapi.json",
    ]);
  });

  it("removes what was in the output directory before", async () => {
    await expect(stat(join(DIST, "stale.txt"))).rejects.toThrow();
  });

  it("writes the entry module under .apiary", async () => {
    const source = await readFile(ENTRY, "utf8");
    expect(source.startsWith("// Generated by @open-apiary/kit.")).toBe(true);
    expect(source).toContain('import e0 from "../src/health";');
    expect(source).toContain('import s0 from "../src/services/clock";');
    expect(source).toContain('"getHealth": e0,');
  });

  it("bundles a default export with the endpoints, the services, and the document", async () => {
    const { default: bundle } = await load(join(DIST, "index.mjs"));
    expect(Object.keys(bundle.endpoints)).toEqual(IDS);
    for (const endpoint of Object.values(bundle.endpoints)) {
      expect(isEndpoint(endpoint)).toBe(true);
    }
    expect(bundle.services).toHaveLength(1);
    expect(isService(bundle.services[0])).toBe(true);
    expect(bundle.services[0]?.name).toBe("Clock");
    const written = JSON.parse(
      await readFile(join(DIST, "openapi.json"), "utf8"),
    );
    expect(bundle.openapi).toEqual(written);
  });

  it("writes a document that reflects the config and the source", async () => {
    const doc = JSON.parse(await readFile(join(DIST, "openapi.json"), "utf8"));
    expect(doc.openapi).toBe("3.1.0");
    expect(doc.info).toEqual({ title: "Fixture API", version: "1.2.3" });
    expect(doc.servers).toEqual([{ url: "/api" }]);
    expect(Object.keys(doc.paths).sort()).toEqual([
      "/health",
      "/users",
      "/users/{id}",
    ]);
    expect(doc.paths["/users/{id}"].get.security).toEqual([
      { bearer: ["users:read"] },
    ]);
    expect(doc.paths["/users"].post.responses).toHaveProperty("201");
  });

  it("writes a declaration that types the bundle", async () => {
    const declaration = await readFile(join(DIST, "index.d.mts"), "utf8");
    expect(declaration).toContain("getHealth");
    expect(declaration).toContain("openapi: Record<string, unknown>");
    expect(declaration).toContain("export declare const endpoints: {");
    expect(declaration).toContain(
      "export declare const services: (typeof Clock)[];",
    );
  });

  it("ends the document file with a newline", async () => {
    const text = await readFile(join(DIST, "openapi.json"), "utf8");
    expect(text.endsWith("}\n")).toBe(true);
  });

  it("rejects a missing config", async () => {
    await expect(
      build({ root: PROJECT, config: "absent.config.ts" }),
    ).rejects.toThrow(MissingConfigError);
  });

  it("rejects an invalid config before it reads the source", async () => {
    await expect(
      build({ root: PROJECT, config: "../configs/invalid.config.ts" }),
    ).rejects.toThrow(InvalidConfigError);
  });
});

describe("generate", () => {
  it("returns the same ids and document as the build, and writes nothing", async () => {
    const config = await loadConfig(join(PROJECT, "apiary.config.ts"));
    const kit = await generate(config, {
      cwd: PROJECT,
      name: "@open-apiary/kit-fixture",
      version: "1.2.3",
    });
    expect(kit.root).toBe(PROJECT);
    expect(kit.outDir).toBe(".dist");
    expect(kit.endpoints.map((endpoint) => endpoint.id)).toEqual(IDS);
    expect(kit.services.map((service) => service.service.name)).toEqual([
      "Clock",
    ]);
    expect(kit.files).toHaveLength(7);
    expect(kit.openapi.info).toEqual({
      title: "Fixture API",
      version: "1.2.3",
    });

    const built = await build({ root: PROJECT });
    const written = JSON.parse(
      await readFile(join(PROJECT, built.outDir, "openapi.json"), "utf8"),
    );
    expect(kit.openapi).toEqual(written);
  }, 60_000);

  it("rejects an invalid config", async () => {
    await expect(
      generate({ source: "./src", outDir: ".." }, { cwd: PROJECT }),
    ).rejects.toThrow(InvalidConfigError);
  });
});
