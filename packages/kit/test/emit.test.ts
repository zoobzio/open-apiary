import type { Kit } from "../src/types";

import { join } from "node:path";
import { apiary, Service } from "@open-apiary/schema";
import { describe, expect, it } from "vitest";
import { z } from "zod";

import { entry, entryPath } from "../src/emit";
import { ROOT, identifiedOf, serviceOf } from "./helpers";

class Clock extends Service {}
class Users extends Service {}

/** A validated build over the fake root, with files of each extension. */
const kit: Kit = {
  endpoints: [
    identifiedOf(
      apiary.GET("/users", {}, z.array(z.string())).handle(() => []),
      "src/users/list.ts",
    ),
    identifiedOf(
      apiary
        .GET("/users/{id}", { path: z.object({ id: z.string() }) }, z.string())
        .handle(() => ""),
      "src/users/get.mjs",
    ),
    identifiedOf(
      apiary.POST("/users", {}, z.string()).handle(() => ""),
      "src/users/create.js",
    ),
  ],
  services: [
    serviceOf(Clock, "src/services/clock.ts"),
    serviceOf(Users, "src/services/users.mts"),
  ],
  openapi: { openapi: "3.1.0", info: { title: "T", version: "1" }, paths: {} },
  root: ROOT,
  outDir: ".dist",
  files: [],
};

describe("entry", () => {
  const source = entry(kit);

  it("starts with the banner", () => {
    expect(
      source.startsWith(
        "// Generated by @open-apiary/kit. Do not edit by hand.\n",
      ),
    ).toBe(true);
  });

  it("imports each file relative to the entry directory, in POSIX form", () => {
    expect(source).toContain('import e0 from "../src/users/list";');
    expect(source).toContain('import e1 from "../src/users/get.mjs";');
    expect(source).toContain('import e2 from "../src/users/create.js";');
    expect(source).toContain('import s0 from "../src/services/clock";');
    expect(source).toContain('import s1 from "../src/services/users.mts";');
  });

  it("keys the endpoints by id in order", () => {
    expect(source).toContain(
      [
        "export const endpoints = {",
        '  "getUsers": e0,',
        '  "getUsersById": e1,',
        '  "postUsers": e2,',
        "};",
      ].join("\n"),
    );
  });

  it("lists the services in order", () => {
    expect(source).toContain("export const services = [s0, s1];");
  });

  it("types the document as a record and inlines it", () => {
    expect(source).toContain(
      'export const openapi: Record<string, unknown> = {\n  "openapi": "3.1.0",',
    );
    expect(source).toContain('"title": "T"');
  });

  it("default-exports the bundle and ends with a newline", () => {
    expect(source).toContain(
      "\nexport default { endpoints, services, openapi };\n",
    );
    expect(source.endsWith("\n")).toBe(true);
  });

  it("writes empty collections when nothing was found", () => {
    const empty = entry({ ...kit, endpoints: [], services: [] });
    expect(empty).toContain("export const endpoints = {\n};");
    expect(empty).toContain("export const services = [];");
    expect(empty).not.toContain("import ");
  });

  it("prefixes a specifier that does not climb out", () => {
    const flat = entry({
      ...kit,
      endpoints: [
        identifiedOf(apiary.GET("/x", {}, z.string()), ".apiary/sub/x.ts"),
      ],
      services: [],
    });
    expect(flat).toContain('import e0 from "./sub/x";');
  });
});

describe("entryPath", () => {
  it("is index.ts under .apiary", () => {
    expect(entryPath()).toBe(join(".apiary", "index.ts"));
  });
});
